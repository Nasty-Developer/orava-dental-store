#!/usr/bin/env node
/**
 * Regenerate docs/IMAGE-QUEUE.md: every product still waiting for a real
 * photograph, featured first, then popular, then the rest, grouped by brand.
 *
 *   npm run images:queue
 */
import fs from "node:fs";
import path from "node:path";
import { readCatalogue } from "./lib/read-catalogue.mjs";

const products = readCatalogue();
const rank = (p) => (p.featured ? 0 : p.popular ? 1 : 2);
const waiting = products.filter((p) => !p.image).sort((a, b) => rank(a) - rank(b) || a.brand.localeCompare(b.brand) || a.name.localeCompare(b.name));

const byBrand = new Map();
for (const p of waiting) {
  if (!byBrand.has(p.brand)) byBrand.set(p.brand, []);
  byBrand.get(p.brand).push(p);
}

const rows = (list) =>
  list
    .map((p) => `| ${p.featured ? "★" : p.popular ? "·" : ""} | ${p.name} | ${p.packaging ?? "—"} | \`${p.slug}\` |`)
    .join("\n");

const out = [
  "# Product photograph queue",
  "",
  `Generated by \`npm run images:queue\` on ${new Date().toISOString().slice(0, 10)}.`,
  "",
  `${waiting.length} of ${products.length} products still show the placeholder illustration.`,
  "★ = featured on the homepage, · = popular. Photograph or licence the ★ rows first: they are the ones visitors see.",
  "",
  "Rules and the licence request template: [IMAGE-SOURCING.md](./IMAGE-SOURCING.md).",
  "",
];

for (const [brand, list] of [...byBrand.entries()].sort((a, b) => b[1].length - a[1].length)) {
  out.push(`## ${brand} (${list.length})`, "", "| | Product | Pack size | slug |", "|---|---|---|---|", rows(list), "");
}

fs.writeFileSync(path.join(process.cwd(), "docs", "IMAGE-QUEUE.md"), out.join("\n"));
console.log(`docs/IMAGE-QUEUE.md: ${waiting.length} products across ${byBrand.size} brands.`);
